const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
require.extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file,'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,file);
const {languages,translations} = require('../lib/i18n.ts');
const read = file => fs.readFileSync(path.join(__dirname,'..',file),'utf8');
for (const {code} of languages) assert.ok(translations[code].search.mobilePlaceholder.length <= 30, code+' compact search copy');
const header = read('components/sections/site-header.tsx');
assert.ok(header.includes('aria-label={dictionary.nav.menuLabel}'));
assert.ok(header.includes('role="dialog"'));
assert.ok(header.includes('min-w-11'));
const focus = read('components/ui/use-modal-focus.ts');
assert.ok(focus.includes('opener.focus({ preventScroll: true })'));
assert.ok(focus.includes('previousOverflow'));
assert.ok(focus.includes('event.shiftKey'));
const search = read('components/sections/search-overlay.tsx');
for(const token of ['h-dvh','max-h-full','min-h-0','overscroll-contain','data-modal-initial-focus','enterKeyHint="search"','useModalFocus(open, close)']) assert.ok(search.includes(token),token);
const panel = read('components/sections/search-panel.tsx');
assert.ok(!panel.includes('truncate'));
assert.ok(panel.includes('mobilePlaceholder'));
assert.ok(!panel.includes('initial={{ opacity: 0'));
const hero = read('components/sections/hero.tsx');
assert.ok(hero.includes('!loadedSlides.includes(active)'));
assert.ok(hero.includes('!loadedSlides.includes(next)'));
assert.ok(hero.includes('quality={70}'));
assert.ok(hero.includes('pt-28'));
const destinations = read('components/sections/featured-destinations.tsx');
assert.ok(destinations.includes('index === 0 || index === featured.length - 1 ?'));
console.log('PASS: mobile UI invariants, compact copy in 4 languages, dialog focus, image scheduling and responsive sizes.');
